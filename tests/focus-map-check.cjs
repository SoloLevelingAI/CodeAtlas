const atlasUrl=(route='/')=>{const url=new URL(route,process.env.ATLAS_URL||'http://127.0.0.1:5278');if(process.env.ATLAS_REPORT)url.searchParams.set('report',process.env.ATLAS_REPORT);return url.href;};
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
 const browser = await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE || undefined});
 const page = await browser.newPage({viewport:{width:1600,height:1000}});
 page.setDefaultTimeout(15000);
 const passed=[], errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const check=(condition,label)=>{assert(condition,label);passed.push(label);console.log('PASS '+label);};
 const nodes=()=>page.locator('#feature-map [data-map-id]').evaluateAll(items=>items.map(n=>[n.dataset.mapId,n.getAttribute('transform')]));
 const branch=id=>page.locator(`#feature-map [data-map-feature="${id}"]`);
 const expand=async node=>{await node.locator('[data-expand]').click();await page.waitForTimeout(80);};
 try {
  await page.goto(atlasUrl(),{waitUntil:'networkidle'});
    await page.locator('#diagram-mode').click();
  const initial=await nodes();
  check(initial.length===6,'canvas starts with six retained module roots');
  const root=branch('atlas.analysis');
  await root.locator('.node-select').click();
  await page.waitForSelector('[data-child="atlas.analysis.inventory"]');
  check(JSON.stringify(await nodes())===JSON.stringify(initial),'selecting module updates details without replacing canvas');
  const before=await root.boundingBox();
  await expand(root);
  await page.waitForSelector('#feature-map [data-map-feature="atlas.analysis.inventory"]');
  check(JSON.stringify(await root.boundingBox())===JSON.stringify(before),'expansion does not move clicked parent on screen');
  const expanded=await nodes();
  check(initial.every(([id,transform])=>expanded.some(item=>item[0]===id&&item[1]===transform)),'existing roots keep their exact canvas coordinates');
  const inventory=branch('atlas.analysis.inventory');
  await expand(inventory);
  check(await page.locator('#feature-map [data-map-symbol="T:CodeAtlas.Storage.SourceRepository"]').count()===1,'child expands types beside retained parent');
  const nested=await nodes();
  await expand(root);
  check((await nodes()).length===6,'collapse hides branch descendants only');
  await expand(root);
  check(JSON.stringify(await nodes())===JSON.stringify(nested),'reopening restores nested branches and their positions');
  await page.locator('[data-child="atlas.analysis.inventory"]').click();
  await page.waitForSelector('[data-node="T:CodeAtlas.Storage.SourceRepository"]');
  check(JSON.stringify(await nodes())===JSON.stringify(nested),'right-side directory navigation does not change map');
  await page.screenshot({path:'artifacts/CodeAtlas-expand-overview.png',fullPage:true});
  const type=page.locator('#feature-map [data-map-symbol="T:CodeAtlas.Storage.SourceRepository"]');
  await expand(type);
  await type.locator('.node-select').click();
  await page.waitForSelector('[data-node] .symbol-name');
  const methodEntry=page.locator('[data-node]').filter({has:page.locator('.symbol-name',{hasText:'ReadAsync'})});
  const id=await methodEntry.getAttribute('data-node');
  const method=page.locator(`#feature-map [data-map-symbol="${id}"]`);
  check(await method.locator('[data-expand]').count()===0,'terminal method has no fake expand control');
  const typeExpanded=await nodes();
  await methodEntry.click();
  await page.waitForFunction(()=>document.querySelector('.inspector h1')?.textContent==='ReadAsync');
  check(JSON.stringify(await nodes())===JSON.stringify(typeExpanded),'method selection preserves every expanded branch');
  await page.locator('#back').click();
  check(JSON.stringify(await nodes())===JSON.stringify(typeExpanded),'history back does not collapse or replace left map');
  await expand(branch('atlas.reports'));
  check(await branch('atlas.analysis.inventory').count()===1 && await branch('atlas.reports.store').count()===1,'multiple modules stay expanded together');
  check(await page.locator('[data-focus-edge]').count()>0,'dependency edges update for visible expanded nodes');
  await page.locator('#toggle-dependencies').click();
  await page.waitForFunction(()=>document.querySelectorAll('[data-focus-edge]').length===0);
  check(await page.locator('[data-parent-edge]').count()>0,'hiding dependencies retains parent-child structure');
  await page.locator('#collapse-map').click();
  await page.waitForFunction(()=>document.querySelectorAll('#feature-map [data-map-id]').length===6);
  check(JSON.stringify(await nodes())===JSON.stringify(initial),'explicit collapse all retains original root positions');
  check(errors.length===0,'no browser errors: '+errors.join(';'));
  fs.writeFileSync('artifacts/focus-map-check.json',JSON.stringify({status:'passed',assertions:passed.length,passed},null,2));
 } catch(e) {await page.screenshot({path:'artifacts/expand-failure.png',fullPage:true});throw e;}
 finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
