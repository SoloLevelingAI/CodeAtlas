const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.BROWSER_EXECUTABLE || undefined});
  const page = await browser.newPage({viewport:{width:1600,height:1000},deviceScaleFactor:1});
  page.setDefaultTimeout(15000);
  const errors = [], passed = [];
  const output = path.join(process.cwd(),'artifacts');
  fs.mkdirSync(output,{recursive:true});
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => {if(message.type() === 'error') errors.push(message.text());});
  const check = (condition, label) => {assert(condition,label);passed.push(label);console.log('PASS ' + label);};
  const heading = text => page.waitForFunction(text => document.querySelector('.inspector h1')?.textContent === text,text);
  const child = async id => {await page.locator(`[data-child="${id}"]`).click();await page.waitForSelector(`[data-crumb="${id}"]`);};
  const select = async (id,name) => {await page.locator(`[data-node="${id}"]`).click();await heading(name);};
  try {
    await page.goto(process.env.ATLAS_URL || 'http://127.0.0.1:5278', {waitUntil:'networkidle'});
    await page.locator('#diagram-mode').click();
    await page.waitForSelector('#feature-map');
    await page.waitForFunction(() => !!window.Blazor && document.querySelector('#report-select')?.value === 'self');
    check(await page.locator('[data-feature]').count() === 6 && await page.locator('[data-node]').count() === 0,'overview has six real modules and no global flat symbol list');
    await page.screenshot({path:path.join(output,'CodeAtlas-hierarchy-overview.png'),fullPage:true});
    await page.locator('[data-feature="atlas.analysis"]').click();
    await page.waitForSelector('[data-child="atlas.analysis.inventory"]');
    check(await page.locator('[data-child]').count() === 3,'analysis opens only three direct subfunctions');
    await child('atlas.analysis.inventory');
    check(await page.locator('[data-node="T:CodeAtlas.Storage.SourceRepository"]').count() === 1 && await page.locator('[data-node="T:CodeAtlas.Contracts.ISourceRepository"]').count() === 1,'inventory holds its own contract and data adapter together');
    check(await page.locator('[data-node="T:CodeAtlas.Storage.JsonReportRepository"]').count() === 0,'unrelated CRUD implementation does not leak into inventory');
    await select('T:CodeAtlas.Storage.SourceRepository','SourceRepository');
    check((await page.locator('#explorer-list').innerText()).includes('遍历仓库'),'member list contains human purpose descriptions');
    await page.locator('[data-node]').filter({has:page.locator('.symbol-name',{hasText:'ReadAsync'})}).click();
    await heading('ReadAsync');
    check((await page.locator('#node-summary').innerText()).includes('遍历仓库'),'method summary comes from source XML');
    check((await page.locator('.io-description').allTextContents()).join(' ').includes('仓库根目录'),'method parameter meaning and return contract visible');
    check((await page.locator('.source-label').innerText()).includes('SourceRepository.cs :'),'method retains precise source location');
    check((await page.locator('.navigation').innerText()).includes('盘点源码'),'breadcrumb retains functional hierarchy');
    await page.locator('#zoom-in').click();
    await page.waitForFunction(() => document.querySelector('#map-viewport')?.getAttribute('transform')?.includes('scale(1.1)'));
    const transform = await page.locator('#map-viewport').getAttribute('transform');
    await page.locator('#pin').click();
    await page.waitForFunction(() => document.querySelector('.pins')?.textContent?.includes('ReadAsync'));
    await page.screenshot({path:path.join(output,'CodeAtlas-hierarchy-method.png'),fullPage:true});
    await page.locator('[data-feature="atlas.reports"]').click();
    await page.waitForSelector('[data-child="atlas.reports.store"]');
    await page.locator('#back').click();
    await heading('ReadAsync');
    check(await page.locator('#map-viewport').getAttribute('transform') === transform,'back restores selected method while map zoom is retained');
    await page.locator('[data-crumb="atlas.analysis"]').click();
    await page.waitForSelector('[data-child="atlas.analysis.csharp"]');
    check(await page.locator('[data-child]').count() === 3,'breadcrumb actually returns to declared parent');
    await page.locator('[data-feature="atlas.explore"]').click();
    await page.waitForSelector('[data-child="atlas.explore.map"]');
    await child('atlas.explore.map');
    check((await page.locator('.facts').innerText()).includes('选中路径') && (await page.locator('.facts').innerText()).includes('源码行'),'page declares purpose inputs and completion outcome');
    await page.locator('[data-crumb="atlas.explore"]').click();
    await page.waitForSelector('[data-child="atlas.explore.navigation"]');
    await child('atlas.explore.navigation');
    await child('atlas.explore.navigation.history');
    await select('T:CodeAtlas.Presentation.GraphExplorerViewModel','GraphExplorerViewModel');
    check((await page.locator('[data-node] .symbol-name').allTextContents()).includes('Back') && !(await page.locator('[data-node] .symbol-name').allTextContents()).includes('ExecuteAsync'),'one ViewModel is navigable by real subtask rather than all methods together');
    await page.locator('#search').fill('恢复功能路径');
    await page.waitForFunction(() => document.querySelectorAll('[data-node]').length === 1 && document.querySelector('[data-node="M:CodeAtlas.Presentation.GraphExplorerViewModel.Back"]'));
    check(await page.locator('[data-node]').count() === 1,'search by method purpose remains within current subtask');
    await page.locator('#search').fill('');
    await page.locator('#quality-panel').click();
    await page.waitForSelector('[data-rule="AT012"]');
    await page.locator('[data-rule="AT012"] summary').click();
    await page.locator('[data-rule="AT012"] [data-finding]').first().click();
    await heading('用途说明缺失');
    check((await page.locator('.purpose-text').innerText()).includes('summary') && await page.locator('#source-code').count() === 1,'missing explanation exposes exact source and repair instruction');
    await page.locator('#unsupported').click();
    await page.waitForSelector('[data-rule="AT200"]');
    await page.locator('#search').fill('Explorer.razor');
    await page.waitForFunction(() => [...document.querySelectorAll('[data-rule="AT200"] [data-finding]')].every(element => element.textContent.includes('Explorer.razor')));
    if (!await page.locator('[data-rule="AT200"]').evaluate(element => element.open)) await page.locator('[data-rule="AT200"] summary').click();
    await page.locator('[data-rule="AT200"] [data-finding]').first().click();
    await heading('明确暂不支持');
    check((await page.locator('#source-code').innerText()).includes('@namespace'),'unsupported source is retained');
    await page.locator('#report-select').selectOption('z-launchdesk');
    await page.waitForSelector('[data-feature="__unassigned__"]');
    check((await page.locator('#overview-map .map-node').textContent()).includes('待归属代码'),'legacy report stays visible in explicit unassigned bucket');
    await page.locator('#report-select').selectOption('self');
    await page.waitForSelector('[data-feature="atlas.analysis"]');
    await page.locator('#workspace-action').click();
    await page.waitForFunction(() => !document.querySelector('#workspace-action')?.disabled,{},{timeout:30000});
    check(await page.locator('.error-banner').count() === 0,'reanalyze preserves valid feature catalog');
    check(errors.length === 0,'no browser errors: ' + errors.join(';'));
    fs.writeFileSync(path.join(output,'browser-check.json'),JSON.stringify({status:'passed',assertions:passed.length,passed},null,2));
    console.log(JSON.stringify({status:'passed',assertions:passed.length,passed},null,2));
  } catch (error) {
    await page.screenshot({path:path.join(output,'browser-failure.png'),fullPage:true});
    console.error(JSON.stringify({heading:await page.locator('.inspector h1').allTextContents(),errors}));
    throw error;
  } finally {await browser.close();}
})().catch(error => {console.error(error);process.exitCode = 1;});
